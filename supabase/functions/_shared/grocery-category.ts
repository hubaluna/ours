export function groceryCategory(
  name: string,
):
  | "Овочі та фрукти"
  | "М’ясо та риба"
  | "Молочні продукти"
  | "Бакалія"
  | "Напої"
  | "Побутові товари"
  | "Інше" {
  const text = name.toLocaleLowerCase("uk").replace(/[’'`]/g, "");
  const rules = [
    [
      "Побутові товари",
      /пральн|миюч|мийни|сервет|папір|туалет|губк|мило|шампун|смітт|зубн|рушник|detergent|soap|tissue/,
    ],
    [
      "Напої",
      /(?:вівсян|мигдал|кокос|соєв).{0,12}молок|вода|води|воду|мінерал|сік|соку|соки|кава|кави|чай|чаю|компот|лимонад|вино|вина|пиво|water|juice|coffee|tea\b/,
    ],
    [
      "М’ясо та риба",
      /мяс|курк|куряч|філе|ялович|свинин|індич|фарш|риба|риби|лосос|хек|скумбр|тунец|тунц|кревет|ковбас|бекон|шинка|chicken|beef|pork|salmon|fish|turkey/,
    ],
    [
      "Молочні продукти",
      /молок|сир|сиру|сметан|вершк|йогурт|кефір|ряжан|яйц|яєц|масло|butter|cheese|milk|cream|yogurt|eggs?/,
    ],
    [
      "Овочі та фрукти",
      /картоп|моркв|цибул|помідор|томат|огір|капуст|буряк|буряк|буряку|брокол|кабач|баклаж|перець|перцю|часник|печериц|гриб|зелень|кроп|петруш|салат|рукол|шпинат|авокад|яблук|банан|апельсин|лимон|ягод|груш|виноград|полуниц|potato|onion|carrot|tomato|cucumber|garlic|apple|banana|lettuce|mushroom/,
    ],
    [
      "Бакалія",
      /рис|греч|булгур|пшон|круп|макарон|паст[аиу]|спагеті|борошн|хліб|лаваш|цукор|цукру|сіль|солі|олія|олії|оливков|соняшник|оцет|мед|горіх|квасол|нут|сочевиц|пластів|вівсян|кускус|спеці|паприк|куркум|rice|pasta|flour|bread|sugar|salt|oil|oats/,
    ],
  ] as const;
  return rules.find(([, expression]) => expression.test(text))?.[0] ?? "Інше";
}
