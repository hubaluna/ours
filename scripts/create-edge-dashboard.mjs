import { readFileSync, writeFileSync } from "node:fs";
const files = [
  "_shared/urls.ts",
  "_shared/metadata.ts",
  "_shared/url-safety.ts",
  "_shared/fetch-page.ts",
  "_shared/preview-handler.ts",
  "link-preview/index.ts",
];
const body = files
  .map(
    (file) =>
      `// ${file}\n` +
      readFileSync(`supabase/functions/${file}`, "utf8")
        .replace(
          /^import[\s\S]*?from\s+["']([^"']+)["'];\s*\n/gm,
          (statement, source) =>
            source.startsWith(".")
              ? ""
              : statement
                  .replace('"linkedom"', '"npm:linkedom@0.18.15"')
                  .replace('"ipaddr.js"', '"npm:ipaddr.js@2.5.0"'),
        )
        .replace(/^export \{ publicUrl \} from .+;\s*\n/gm, ""),
  )
  .join("\n");
writeFileSync(
  "supabase/link-preview-dashboard.ts",
  `// Generated by npm run setup:edge.\n// Paste this entire file in Supabase Dashboard -> Edge Functions -> link-preview.\n// Turn OFF the legacy gateway JWT toggle: the handler verifies user tokens itself.\n${body}`,
);
