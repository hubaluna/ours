import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const migrations = readdirSync("supabase/migrations")
  .filter((name) => /^\d+.*\.sql$/.test(name))
  .sort();

const body = migrations
  .map(
    (name) =>
      `-- ${name}\n` +
      readFileSync(`supabase/migrations/${name}`, "utf8")
        .replace(/^begin;\s*$/gm, "")
        .replace(/^commit;\s*$/gm, "")
        .replace(
          /^create extension if not exists pg_net with schema extensions;\s*$/gm,
          () =>
            `do $$\nbegin\n  create extension if not exists pg_net with schema extensions;\nexception when others then\n  null;\nend $$;`,
        ),
  )
  .join("\n");

writeFileSync(
  "supabase/setup.sql",
  `-- ours. One-time setup for a fresh Supabase project.\n-- Generated by npm run setup:sql. Run the entire file once in SQL Editor.\nbegin;\n${body}\ncommit;\n`,
);
