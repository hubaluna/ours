import { readFileSync, writeFileSync } from "node:fs";
const migrations = [
  "001_core.sql",
  "002_storage_realtime.sql",
  "003_compact_movies_activity.sql",
  "004_recipes_movie_ratings.sql",
  "005_recipe_catalog_shared_menu.sql",
  "006_tiktok_video_recipes.sql",
];
const body = migrations
  .map(
    (name) =>
      `-- ${name}\n` +
      readFileSync(`supabase/migrations/${name}`, "utf8")
        .replace(/^begin;\s*$/gm, "")
        .replace(/^commit;\s*$/gm, ""),
  )
  .join("\n");
writeFileSync(
  "supabase/setup.sql",
  `-- ours. One-time setup for a fresh Supabase project.\n-- Generated by npm run setup:sql. Run the entire file once in SQL Editor.\nbegin;\n${body}\ncommit;\n`,
);
